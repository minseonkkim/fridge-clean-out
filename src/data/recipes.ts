import { INGREDIENT_BY_ID } from "./ingredients.ts";
import type { Recipe, RecipeIngredient, RecipeStep, Tool } from "../lib/domain/types.ts";

/**
 * MVP 레시피 (목표 100개 이상). 결정 D3에 따라 직접 작성했다.
 *
 * 작성 규칙
 * - 사용량은 재료 사전의 기본 단위로 쓴다. 단위는 사전에서 자동으로 붙는다.
 * - alt(...)는 필수 대체 그룹이다. 그중 하나만 있으면 된다 (예: 밥 또는 즉석밥).
 * - opt(...)는 선택 재료다. 없어도 요리가 된다.
 * - 기본 양념(간장·소금 등)도 적는다. 플래너는 기본 양념을 있다고 가정한다.
 * - 가스레인지·냄비·프라이팬은 있다고 가정하고, tools에는 전자레인지·에어프라이어·오븐만 적는다.
 */

type Pair = [ingredientId: string, amount: number];
interface Group {
  required: boolean;
  options: Pair[];
}
type StepDef = string | [text: string, timerSec: number];

const req = (id: string, amount: number): Group => ({ required: true, options: [[id, amount]] });
const opt = (id: string, amount: number): Group => ({ required: false, options: [[id, amount]] });
const alt = (...options: Pair[]): Group => ({ required: true, options });

/** 밥: 지어 둔 밥 또는 즉석밥 */
const RICE = alt(["cooked_rice", 1], ["instant_rice", 1]);

interface Meta {
  min: number;
  diff?: 1 | 2 | 3;
  serv?: number;
  tools?: Tool[];
}

function recipe(id: string, name: string, meta: Meta, groups: Group[], steps: StepDef[]): Recipe {
  const ingredients: RecipeIngredient[] = groups.flatMap((group, index) =>
    group.options.map(([ingredientId, amount]) => {
      const ingredient = INGREDIENT_BY_ID.get(ingredientId);
      if (!ingredient) throw new Error(`레시피 ${id}: 재료 사전에 없는 재료 ${ingredientId}`);
      return {
        groupNo: index + 1,
        ingredientId,
        required: group.required,
        amount,
        unit: ingredient.defaultUnit,
      };
    }),
  );
  return {
    id,
    name,
    minutes: meta.min,
    difficulty: meta.diff ?? 1,
    servings: meta.serv ?? 1,
    tools: meta.tools ?? [],
    steps: steps.map((s): RecipeStep =>
      typeof s === "string" ? { text: s } : { text: s[0], timerSec: s[1] },
    ),
    ingredients,
    imageKey: null,
    source: "manual",
  };
}

